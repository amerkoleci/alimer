using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Alimer.SourceGenerators;

[Generator(LanguageNames.CSharp)]
internal sealed class TypeMetadataGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        DebugGuard.MaybeLaunchDebuggerOnStartup();

        IncrementalValueProvider<ImmutableArray<INamedTypeSymbol?>> collectedSymbols = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => IsValidCandidate(node),
            static (ctx, _) => GetSemanticTarget(ctx)
            ).Collect();

        context.RegisterSourceOutput(collectedSymbols, Execute);
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<INamedTypeSymbol?> symbols)
    {
        if (symbols.IsDefaultOrEmpty)
            return;

        List<INamedTypeSymbol> uniqueSymbols = [.. symbols.Distinct(SymbolEqualityComparer.Default).OfType<INamedTypeSymbol>()];

        foreach (INamedTypeSymbol symbol in uniqueSymbols)
        {
            string source = Build(symbol);
            context.AddSource(GetHintName(symbol), source);
        }

        // Generate a module initializer to register all types with the metadata registry
        GenerateModuleInit(context, uniqueSymbols);
    }

    private static string GetHintName(INamedTypeSymbol type) =>
        type.Name.Replace('.', '_').Replace('+', '_') + ".g.cs";

    private static void GenerateModuleInit(SourceProductionContext context, List<INamedTypeSymbol> types)
    {
        FormattedBuilder builder = new(new StringBuilder());
        builder
            .AppendAutoGenerated()
            .AppendLine()
            .AppendLine("using System.Runtime.CompilerServices;")
            .AppendLine()
            .AppendLine($"namespace Alimer;")
            .AppendLine()
            .AppendLine($"internal static partial class ModuleInit")
            .AppendOpenBracer()
                .AppendLineUndindented($"#pragma warning disable CA2255")
                .AppendLine($"[ModuleInitializer]")
                .AppendLineUndindented($"#pragma warning restore CA2255")
                .AppendLine($"public static void Register()")
                .AppendOpenBracer()
                ;

        foreach (INamedTypeSymbol symbol in types)
        {
            if (symbol is null)
                continue;

            //if (symbol.DerivesFrom("global::Alimer.Engine.Component"))
            {
                builder.AppendLine($"{symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}.Register();");
            }
        }
        builder.AppendLine($"global::Alimer.MetadataRegistry.Prepare();");

        builder
            .AppendCloseBracer()
            .AppendCloseBracer()
            ;

        string moduleInitSource = builder.ToString();

        context.AddSource("ModuleInit.g.cs", SourceText.From(moduleInitSource, Encoding.UTF8));
    }

    public static bool IsValidCandidate(SyntaxNode node)
    {
        // TODO: Should we support enums?
        if (node.IsEnum())
            return false;

        if (node.IsInterface())
            return false;

        if (!node.IsPartial())
            return false;

        return node.IsClass() || node.IsStruct();
    }

    private static INamedTypeSymbol? GetSemanticTarget(GeneratorSyntaxContext ctx)
    {
        return ctx.Node switch
        {
            ClassDeclarationSyntax classDeclaration => GetSemanticTarget(ctx.SemanticModel.GetDeclaredSymbol(classDeclaration) as INamedTypeSymbol),
            StructDeclarationSyntax structDeclaration => GetSemanticTarget(ctx.SemanticModel.GetDeclaredSymbol(structDeclaration) as INamedTypeSymbol),
            EnumDeclarationSyntax enumDeclaration => GetSemanticTarget(ctx.SemanticModel.GetDeclaredSymbol(enumDeclaration) as INamedTypeSymbol),
            _ => null,
        };
    }

    private static INamedTypeSymbol? GetSemanticTarget(INamedTypeSymbol? symbol)
    {
        if (symbol is null)
            return null;

        // Class has MetaAttribute
        if (HasMetaAttribute(symbol))
        {
            return symbol;
        }

        for (INamedTypeSymbol? @base = symbol.BaseType; @base != null; @base = @base.BaseType)
        {
            if (HasMetaAttribute(@base))
            {
                return symbol;
            }
        }

        return null;
    }

    private static bool HasMetaAttribute(ISymbol symbol)
    {
        return symbol.GetAttributes().Any(attr => attr.AttributeClass?.ToDisplayString() == AlimerTypes.MetaAttributeFullName);
    }


    public static string Build(in INamedTypeSymbol symbol)
    {
        string className = symbol.Name;
        string namespaceName = symbol.ContainingNamespace.ToDisplayString();

        FormattedBuilder builder = new(new StringBuilder());

        builder
            .AppendAutoGenerated()
            .AppendLine()
            .AppendLine($"namespace {namespaceName};")
            .AppendLine()
            .AppendLine($"{symbol.DeclaredAccessibility.ToDisplayString()} partial class {className}")
            .AppendOpenBracer()
                .AppendLine($"internal static void Register()")
                .AppendOpenBracer();

        //if (symbol.DerivesFrom("global::Alimer.Engine.Component"))
        //{
        //    builder.AppendLine($"// COMPONENT");
        //}

        ImmutableArray<ISymbol> members = symbol.GetMembers();
        FormattedBuilder propertiesBuilder = new();
        FormattedBuilder fieldsBuilder = new();
        foreach (ISymbol member in members)
        {
            if (!IsExposed(member))
                continue;

            string name = member.Name;
            if (member is IPropertySymbol property)
            {
                if (property.IsStatic || property.IsReadOnly || property.IsWriteOnly)
                    continue;

                if (property.ShouldIgnore())
                    continue;

                string propertyTypeName = property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string getLambda = property.GetMethod is not null && property.GetMethod.DeclaredAccessibility == Accessibility.Public
                    ? $"(obj) => (({className})obj).{property.Name}" : "default";
                string setLambda = property.SetMethod is not null && property.SetMethod.DeclaredAccessibility == Accessibility.Public
                    ? $"(obj, val) => (({className})obj).{property.Name} = ({propertyTypeName})val" : "default";

                propertiesBuilder.Indent(4);
                propertiesBuilder.AppendLine($@"new PropertyMetadata(");
                propertiesBuilder.Indent(1);
                propertiesBuilder.AppendLine($@"name: ""{name}"",");
                propertiesBuilder.AppendLine($@"propertyType: typeof({propertyTypeName}),");
                propertiesBuilder.AppendLine($@"getValue: {getLambda},");
                propertiesBuilder.AppendLine($@"setValue: {setLambda},");
                BuildAttributesList(propertiesBuilder, member.GetAttributes(), "attributes");
                propertiesBuilder.Dedent(1);
                propertiesBuilder.AppendLine($@"),");
                propertiesBuilder.Dedent(4);
            }
            else if (member is IFieldSymbol field)
            {
                if (field.IsStatic || field.IsReadOnly || field.IsImplicitlyDeclared)
                    continue;

                if (field.ShouldIgnore())
                    continue;

                string fieldTypeName = field.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string getLambda = field.DeclaredAccessibility == Accessibility.Public
                    ? $"(obj) => (({className})obj).{field.Name}" : "default";
                string setLambda = field.DeclaredAccessibility == Accessibility.Public
                    ? $"(obj, val) => (({className})obj).{field.Name} = ({fieldTypeName})val" : "default";

                fieldsBuilder.Indent(4);
                fieldsBuilder.AppendLine($@"new FieldMetadata(");
                fieldsBuilder.Indent(1);
                fieldsBuilder.AppendLine($@"name: ""{name}"",");
                fieldsBuilder.AppendLine($@"fieldType: typeof({fieldTypeName}),");
                fieldsBuilder.AppendLine($@"getValue: {getLambda},");
                fieldsBuilder.AppendLine($@"setValue: {setLambda},");
                BuildAttributesList(fieldsBuilder, member.GetAttributes(), "attributes");
                fieldsBuilder.Dedent(1);
                fieldsBuilder.AppendLine($@"),");
                fieldsBuilder.Dedent(4);
            }
            else if (member is IMethodSymbol method)
            {
            }
        }

        string propertiesBuilderString = propertiesBuilder.ToString();
        string fieldsBuilderString = fieldsBuilder.ToString();

        string registerTypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string createFactory = "default";
        if (!symbol.IsAbstract)
        {
            createFactory = $"() => new {registerTypeName}()";
        }

        builder.AppendLine($"global::Alimer.MetadataRegistry.RegisterObjectType(");
        builder.Indent(1);
        builder.AppendLine($"type: typeof({registerTypeName}), ");
        builder.AppendLine($"createObject: {createFactory}, ");

        // Properties
        builder.AppendLine($@"properties:");
        if (!string.IsNullOrEmpty(propertiesBuilderString))
        {
            builder.AppendLine("[");
            builder.AppendLineUndindented($"{propertiesBuilderString}");
            builder.AppendLine("],");
        }
        else
        {
            builder.AppendLine("[],");
        }
        // Fields
        builder.AppendLine($@"fields:");
        if (!string.IsNullOrEmpty(fieldsBuilderString))
        {
            builder.AppendLine("[");
            builder.AppendLineUndindented($"{fieldsBuilderString}");
            builder.AppendLine("],");
        }
        else
        {
            builder.AppendLine("[],");
        }
        BuildAttributesList(builder, symbol.GetAttributes(), "attributes");
        builder.Dedent(1);
        builder.AppendLine(");");

        // Handle EntitySystemAttribute
        foreach (AttributeData attr in symbol.GetAttributes())
        {
            if (attr.AttributeClass is null)
                continue;

            if (attr.AttributeClass.Name == "EntitySystemAttribute")
            {
                TypedConstant typedConstant = attr.ConstructorArguments[0];

                if (typedConstant.Value is ITypeSymbol typeSymbol)
                {
                    string valueTypeName = typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    builder.AppendLine($"global::Alimer.Engine.EntityManager.RegisterSystemFactory((services) => new {valueTypeName}(services));");
                }
            }
        }

        builder
            .AppendCloseBracer()
        //.Serialize(symbol)
        .AppendCloseBracer()
    ;

        return builder.ToString();
    }

    private static bool IsExposed(ISymbol symbol) =>
            symbol.DeclaredAccessibility == Accessibility.Public || symbol.DeclaredAccessibility == Accessibility.Internal;

    private static void BuildAttributesList(FormattedBuilder builder, ImmutableArray<AttributeData> attributes, string propertyName = "attributes")
    {
        if (attributes.IsDefaultOrEmpty)
        {
            builder.AppendLine($@"{propertyName}: []");
            return;
        }

        builder.AppendLine($@"{propertyName}:");
        builder.AppendLine($@"[");

        foreach (AttributeData attribute in attributes)
        {
            if (attribute.AttributeClass is null)
                continue;

            builder.Indent(1);
            builder.AppendLine($"{BuildAttributeInstantiation(attribute)}, ");
            builder.Dedent(1);
        }

        builder.AppendLine($@"]");
    }

    private static string BuildAttributeInstantiation(AttributeData attribute)
    {
        string attributeClassName = attribute.AttributeClass!.ToDisplayString();
        IEnumerable<string> positionalArgs = attribute.ConstructorArguments.Select(FormatTypedConstant);
        IEnumerable<string> namedArgs = attribute.NamedArguments.Select(na => $"{na.Key} = {FormatTypedConstant(na.Value)}");
        string constructorCall = string.Join(", ", positionalArgs);
        string initializers = namedArgs.Any() ? $" {{ {string.Join(", ", namedArgs)} }}" : "";
        return $"new {attributeClassName}({constructorCall}){initializers}";
    }

    private static string FormatTypedConstant(TypedConstant constant)
    {
        if (constant.Kind == TypedConstantKind.Array)
            return $"new[] {{ {string.Join(", ", constant.Values.Select(FormatTypedConstant))} }}";
        if (constant.Value is null) return "null";
        if (constant.Value is bool b) return b ? "true" : "false";
        if (constant.Value is string s) return $"\"{s.Replace("\"", "\\\"")}\"";
        if (constant.Value is char c) return $"'{c}'";
        if (constant.Value is ITypeSymbol typeSymbol) return $"typeof({typeSymbol.ToDisplayString()})";
        if (constant.Type?.TypeKind == TypeKind.Enum) return $"({constant.Type.ToDisplayString()}){constant.Value}";
        return constant.Value.ToString();
    }
}

public static class Code
{
    // Handwritten regex for nameof() expressions. Group 1 is what you want.
    public const string NAME_OF = @"(?:(?<=\.)?([^.<>\n]*)(?:<[^.\n]+>)?(?=$))";
    public static Regex NameOfRegex { get; set; } = new Regex(NAME_OF);

    /// <summary>
    /// Compute the nameof expression for a given string.
    /// </summary>
    /// <param name="input">Input text.</param>
    /// <returns>Equivalent value that nameof() would produce.</returns>
    public static string NameOf(string input)
    {
        var text = input.StartsWith("nameof(") ?
          input.Substring(7, input.Length - 8)
          : input;

        var match = NameOfRegex.Match(text);

        return match.Success ? match.Groups[1].Value : text;
    }
    /// <summary>
    /// Compute the nameof expression for a given string.
    /// </summary>
    /// <param name="input">Input text.</param>
    /// <returns>Equivalent value that nameof() would produce.</returns>
    public static string TypeOf(string input)
    {
        var text = input.StartsWith("typeof(") ?
          input.Substring(7, input.Length - 8)
          : input;

        var match = NameOfRegex.Match(text);

        return match.Success ? match.Groups[1].Value : text;
    }
}

internal static class FormattedBuilderExtensions
{
    public static FormattedBuilder Serialize(this FormattedBuilder builder, INamedTypeSymbol symbol)
    {
        if (symbol.IsAbstract)
            return builder;

        builder = builder
            .AppendLine()
            .AppendLine($"public override JsonObject Serialize()")
            .AppendOpenBracer()
                .AppendLine($"JsonObject json = new ()")
                .AppendOpenBracer()
                .AppendLine("{ \"__type\", " + $"\"{symbol.Name}\"" + " },")
                .AppendLine("{ \"__enabled\", " + $"IsEnabled" + " },")
                .AppendCloseBracer(";")
                .AppendLine()
                ;

        foreach (IPropertySymbol property in symbol.GetMembers().OfType<IPropertySymbol>())
        {
            if (property.IsStatic || property.IsReadOnly)
                continue;

            if (ShouldIgnore(property))
                continue;

            string jsonName = $"\"{property.Name}\"";

            switch (property.Type.SpecialType)
            {
                case SpecialType.System_Boolean:
                case SpecialType.System_SByte:
                case SpecialType.System_Int16:
                case SpecialType.System_Int32:
                case SpecialType.System_Int64:
                case SpecialType.System_Byte:
                case SpecialType.System_UInt16:
                case SpecialType.System_UInt32:
                case SpecialType.System_UInt64:
                case SpecialType.System_Single:
                case SpecialType.System_Double:
                case SpecialType.System_Char:
                case SpecialType.System_String:
                    builder = builder.AppendLine($"json.Add({jsonName}, {property.Name});");
                    break;
                default:
                    builder = builder.AppendLine($"json.Add({jsonName}, JsonUtilities.ToNode({property.Name}));");
                    break;
            }
        }

        return builder
            .AppendLine("return json;")
            .AppendCloseBracer()
                ;
    }

    public static bool ShouldIgnore(this ISymbol symbol)
    {
        if (symbol == null)
            throw new ArgumentNullException(nameof(symbol));

        AttributeData? jsonAttribute = symbol.GetAttributes().FirstOrDefault(attr => attr.AttributeClass!.Name == "IgnoreDataMemberAttribute");
        if (jsonAttribute != null)
        {
            return true;
        }

        jsonAttribute = symbol.GetAttributes().FirstOrDefault(attr => attr.AttributeClass!.Name == "JsonIgnoreAttribute");
        if (jsonAttribute != null)
        {
            return true;
        }

        return false;
    }
}

